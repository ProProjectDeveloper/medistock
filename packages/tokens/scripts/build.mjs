// Generates tokens.css (CSS custom properties) from tokens.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));

const vars = (obj, prefix = '', unit = '') =>
  Object.entries(obj).map(([k, v]) => `  --${prefix}${k}: ${typeof v === 'number' ? v + unit : v};`).join('\n');

const css = `/* Generated by packages/tokens/scripts/build.mjs from tokens.json. Do not edit by hand. */
:root {
${vars(t.color.light)}
${vars(t.fontSize, 'fs-', 'px')}
${vars(t.radius, 'r-', 'px')}
  --font-display: ${t.font.display};
  --font-body: ${t.font.body};
  --font-mono: ${t.font.mono};
  --shadow-raised: ${t.shadow.raised};
  --shadow-overlay: ${t.shadow.overlay};
  --ease: ${t.motion.ease};
  --dur-fast: ${t.motion.fast};
  --dur-base: ${t.motion.base};
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${vars(t.color.dark).replace(/^/gm, '  ')}
    --shadow-raised: 0 1px 2px rgba(0,0,0,.4), 0 2px 8px rgba(0,0,0,.3);
    --shadow-overlay: 0 12px 32px rgba(0,0,0,.55);
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${vars(t.color.dark)}
  --shadow-raised: 0 1px 2px rgba(0,0,0,.4), 0 2px 8px rgba(0,0,0,.3);
  --shadow-overlay: 0 12px 32px rgba(0,0,0,.55);
  color-scheme: dark;
}
`;
writeFileSync(join(root, 'tokens.css'), css);
console.log('tokens.css written');
