// Writes supabase/seed.sql from the same generator the demo mode uses.
// Dates are emitted relative to current_date/now(), so seeding on any day gives every expiry band.
// Usage: npm run seed:sql
import { generateSeed } from '../packages/core/src/demo/seed.ts';
import { toRow } from '../packages/core/src/supabase/mapping.ts';
import { daysBetween, todayISO } from '../packages/core/src/util.ts';

const today = todayISO();
const ds = generateSeed(today);
const base = Date.now();

const lit = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
};
const rel = (col: string, v: unknown): string => {
  if (typeof v !== 'string') return lit(v);
  if (/^\d{4}-\d{2}-\d{2}$/.test(v) && /(date|expected_at)$/.test(col)) return `current_date + ${daysBetween(today, v)}`;
  if (/^\d{4}-\d{2}-\d{2}T/.test(v) && /_at$/.test(col)) {
    const mins = Math.round((Date.parse(v) - base) / 60000);
    return `now() + interval '${mins} minutes'`;
  }
  return lit(v);
};
// Seed rows have no auth users yet, so person references are left empty.
const PEOPLE = new Set(['user_id', 'created_by']);

function insert(table: string, rows: Record<string, unknown>[]) {
  if (!rows.length) return '';
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => (PEOPLE.has(c) ? 'null' : rel(c, r[c]))).join(', ')})`).join(',\n');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values};\n\n`;
}

let sql = `-- Generated by scripts/generate-seed-sql.ts. Demo data: ${ds.medicines.length} medicines, ${ds.batches.length} batches, ${ds.suppliers.length} suppliers.\n\n`;
const { id: _id, ...settings } = toRow.settings(ds.settings);
sql += `update public.settings set ${Object.entries(settings).map(([k, v]) => `${k} = ${lit(v)}`).join(', ')} where id = 1;\n\n`;
sql += insert('locations', ds.locations.map(toRow.location));
sql += insert('suppliers', ds.suppliers.map(toRow.supplier));
sql += insert('medicines', ds.medicines.map(toRow.medicine));
sql += insert('batches', ds.batches.map(toRow.batch));
sql += insert('stock_movements', ds.movements.map(toRow.movement));
sql += insert('purchase_orders', ds.purchaseOrders.map(toRow.purchaseOrder));
sql += insert('po_lines', ds.purchaseOrders.flatMap((p) => p.lines).map(toRow.poLine));
process.stdout.write(sql);
